def get_phone_name(model_code: str) -> str:
    """Возвращает название смартфона и его код или исходный код при отсутствии в базе"""
    if not model_code:
        return "Неизвестное устройство"
    
    clean_code = model_code.strip()
    
    # 1. Прямой поиск в словаре по техническому коду
    if clean_code in PHONE_MODELS:
        return f"{PHONE_MODELS[clean_code]} ({clean_code})"
    
    # 2. Если устройство уже прислало коммерческое имя напрямую
    for code, name in PHONE_MODELS.items():
        if clean_code.lower() == name.lower():
            return f"{name} ({code})"

    return clean_code

